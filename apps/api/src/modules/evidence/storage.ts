// Where evidence files live (docs/17 §4): local disk in development, a private
// Cloudflare R2 bucket in staging and production. Files are always served
// through the API, so every access is checked and the original's access is
// logged (docs/10 §3.2). Keys are opaque ids, never user file names.

import {
  DeleteObjectCommand,
  GetObjectCommand,
  PutObjectCommand,
  S3Client,
} from "@aws-sdk/client-s3";
import { createReadStream, createWriteStream } from "node:fs";
import { mkdir, rm, stat } from "node:fs/promises";
import { dirname, resolve, sep } from "node:path";
import { Readable } from "node:stream";
import { pipeline } from "node:stream/promises";
import type { Env } from "../../config/env";

export interface EvidenceStorage {
  /** Copies a finished local file into storage under `key`. */
  putFile(key: string, localPath: string, contentType: string): Promise<void>;
  /** A stream of the stored file, or null if it doesn't exist. */
  read(key: string): Promise<Readable | null>;
  delete(key: string): Promise<void>;
}

export const EVIDENCE_STORAGE = Symbol("EVIDENCE_STORAGE");

class LocalStorage implements EvidenceStorage {
  private readonly root: string;
  constructor(dir: string) {
    this.root = resolve(dir);
  }

  private pathOf(key: string) {
    const p = resolve(this.root, key);
    // Keys are generated by us, but never let one escape the folder.
    if (!p.startsWith(this.root + sep)) throw new Error("Invalid storage key");
    return p;
  }

  async putFile(key: string, localPath: string) {
    const target = this.pathOf(key);
    await mkdir(dirname(target), { recursive: true });
    await pipeline(createReadStream(localPath), createWriteStream(target, { flags: "wx" }));
  }

  async read(key: string) {
    const p = this.pathOf(key);
    try {
      await stat(p);
    } catch {
      return null;
    }
    return createReadStream(p);
  }

  async delete(key: string) {
    await rm(this.pathOf(key), { force: true });
  }
}

class R2Storage implements EvidenceStorage {
  private readonly client: S3Client;
  constructor(
    endpoint: string,
    accessKeyId: string,
    secretAccessKey: string,
    private readonly bucket: string,
  ) {
    this.client = new S3Client({
      region: "auto",
      endpoint,
      credentials: { accessKeyId, secretAccessKey },
    });
  }

  async putFile(key: string, localPath: string, contentType: string) {
    const { size } = await stat(localPath);
    await this.client.send(
      new PutObjectCommand({
        Bucket: this.bucket,
        Key: key,
        Body: createReadStream(localPath),
        ContentLength: size,
        ContentType: contentType,
      }),
    );
  }

  async read(key: string) {
    try {
      const res = await this.client.send(new GetObjectCommand({ Bucket: this.bucket, Key: key }));
      return (res.Body as Readable | undefined) ?? null;
    } catch (err) {
      if ((err as { name?: string }).name === "NoSuchKey") return null;
      throw err;
    }
  }

  async delete(key: string) {
    await this.client.send(new DeleteObjectCommand({ Bucket: this.bucket, Key: key }));
  }
}

export function createEvidenceStorage(env: Env): EvidenceStorage {
  if (env.EVIDENCE_STORAGE === "r2") {
    return new R2Storage(
      env.R2_ENDPOINT!,
      env.R2_ACCESS_KEY!,
      env.R2_SECRET_KEY!,
      env.R2_BUCKET_NAME!,
    );
  }
  return new LocalStorage(env.EVIDENCE_DIR);
}
